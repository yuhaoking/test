/** 转换入口：先词表（长词优先）后字表 */
export function toTraditional(text: string): string {
  let out = String(text ?? '');
  if (!out) return out;
  // 长词优先，避免「文件夹」先被「文件」切走
  for (const [s, t] of [...PHRASES].sort((a, b) => b[0].length - a[0].length)) {
    if (out.includes(s)) out = out.split(s).join(t);
  }
  let converted = '';
  for (const ch of out) converted += CHARS[ch] ?? ch;
  return converted;
}

